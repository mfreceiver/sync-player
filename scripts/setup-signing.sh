#!/usr/bin/env bash
# scripts/setup-signing.sh — 从凭据管理器重新生成 local.properties 的 release.* 签名配置。
#
# local.properties 是 gitignored 且位于仓库内，可能被仓库操作误清（如 stray `> local.properties`）。
# 凭据的 source of truth 在仓库外（凭据管理器）；本脚本负责重新注入。丢了 local.properties
# 就重跑本脚本。
#
# Source priority:
#   1. `pass` 条目（GPG 加密，首选）: sync-player/release/{store-file,store-password,key-alias,key-password}
#      （与 ocdroid / x-liker 家族一致）
#   2. $SYNC_PLAYER_RELEASE_CREDS 平文件（默认 /home/mar/.android/sync-player_release.creds，
#      mode 600，仓库外）。FALLBACK。
#
# 用法: ./scripts/setup-signing.sh
# 配合: ./scripts/gitea/setup-secrets.sh 把同一份凭据推到 Gitea Secrets 供 CI 使用。
set -euo pipefail

CREDS="${SYNC_PLAYER_RELEASE_CREDS:-/home/mar/.android/sync-player_release.creds}"
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
LP="$ROOT/local.properties"

PASS_PREFIX="sync-player/release"
PASS_HAS() { command -v pass >/dev/null 2>&1 && pass show "$PASS_PREFIX/$1" >/dev/null 2>&1; }

# fetch <pass_dash_key> <creds_camel_key>  -> echoes value (pass first, creds fallback, else empty)
fetch() {
    local dash="$1" camel="$2"
    if PASS_HAS "$dash"; then
        pass show "$PASS_PREFIX/$dash" | tr -d '\n'
    elif [ -f "$CREDS" ]; then
        grep -E "^release\.${camel}=" "$CREDS" | head -1 | cut -d= -f2-
    fi
}

STORE_FILE="$(fetch store-file storeFile || true)"
STORE_PW="$(fetch store-password storePassword || true)"
KEY_ALIAS="$(fetch key-alias keyAlias || true)"
KEY_PW="$(fetch key-password keyPassword || true)"

if [ -z "${STORE_FILE:-}" ] || [ -z "${STORE_PW:-}" ]; then
    echo "setup-signing: ❌ 读不到 release.storeFile/storePassword。" >&2
    echo "  请配置 pass（$PASS_PREFIX/*）或提供 $CREDS / 设 SYNC_PLAYER_RELEASE_CREDS。" >&2
    exit 1
fi
[ -z "${KEY_ALIAS:-}" ] && KEY_ALIAS=release
[ -z "${KEY_PW:-}" ] && KEY_PW="$STORE_PW"

# 保留既有 local.properties 的所有非 release.* 键值行（sdk.dir / java.home 等）；
# 仅重写 release.* 块。无既有文件时回退默认 sdk.dir。
KEEP=""
if [ -f "$LP" ]; then
    # 保留 key=value 形式、且不以 release. 开头、且非本脚本旧注释的行。
    KEEP="$(grep -E '^[a-zA-Z][a-zA-Z0-9._-]*=' "$LP" | grep -v '^release\.' || true)"
fi
[ -z "$KEEP" ] && KEEP="sdk.dir=/home/mar/android-sdk"

# 报告用了哪个来源。
SRC="pass"
PASS_HAS store-password || SRC="$CREDS"

umask 077
{
    printf '%s\n' "$KEEP"
    echo "# release signing — regenerated by scripts/setup-signing.sh (source: $SRC)"
    echo "# (请勿手改 release.* 行；改凭据管理器后重跑本脚本)"
    printf 'release.storeFile=%s\n'        "$STORE_FILE"
    printf 'release.storePassword=%s\n'    "$STORE_PW"
    printf 'release.keyAlias=%s\n'         "$KEY_ALIAS"
    printf 'release.keyPassword=%s\n'      "$KEY_PW"
} > "$LP"
chmod 600 "$LP"

echo "setup-signing: 写入 $LP (source: $SRC)"
echo "  keystore: $STORE_FILE"
echo "  alias:    $KEY_ALIAS"
